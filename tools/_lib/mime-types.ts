/** Case-insensitive search across ext, mime, category and description. */
export function searchMime(query: string, limit = 200): MimeEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return MIME_ENTRIES.slice(0, limit);
  const noDot = q.startsWith(".") ? q.slice(1) : q;
  return MIME_ENTRIES.filter(
    (e) =>
      e.ext === noDot ||
      e.mime.toLowerCase().startsWith(noDot) ||
      e.mime.toLowerCase().includes(noDot) ||
      e.desc.toLowerCase().includes(noDot) ||
      e.category === noDot,
  ).slice(0, limit);
}

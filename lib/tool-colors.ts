export function toolHue(slug: string, category: string): number {
  return TOOL_HUE[slug] ?? CATEGORY_HUE[category as CategoryId] ?? 222;
}

/** Inline style: tinted tile bg + matching icon color, adapts to dark mode via light-dark(). */
export function tileStyle(slug: string, category: string): React.CSSProperties {
  const h = toolHue(slug, category);
  return {
    background: `light-dark(hsl(${h} 90% 94%), hsl(${h} 40% 22%))`,
    color: `light-dark(hsl(${h} 65% 40%), hsl(${h} 70% 72%))`,
  };
}
